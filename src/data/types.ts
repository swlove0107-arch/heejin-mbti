// 동물 캐릭터 정보 인터페이스
export interface CharacterInfo {
  animal: string; // 동물 종류 (예: '부엉이', '사자')
  name: string;   // 동물에 어울리게 창작한 캐릭터 이름 (예: '지혜로운 부엉 교수')
}

// 16가지 MBTI 유형별 상세 설명 데이터 인터페이스
export interface MBTITypeInfo {
  code: string;              // 유형 코드 (예: 'INTJ', 'ENFP')
  nickname: string;          // 한글 별명 (예: '밤하늘을 읽는 전략가')
  summary: string;           // 한 줄 소개
  description: string;       // 성격 상세 설명 (3~4문장)
  strengths: string[];       // 강점 3가지
  cautions: string[];        // 조심할 점 2가지
  compatibleTypes: string[]; // 잘 맞는 유형 2가지 (유형 코드)
  color: string;             // 대표 파스텔 톤 색상 (HEX)
  character: CharacterInfo;  // 지정된 동물 및 캐릭터 이름
}

